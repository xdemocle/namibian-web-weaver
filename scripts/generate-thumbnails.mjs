/**
 * Generates responsive thumbnails for every photo shown on the site.
 *
 *   bun run thumbs
 *
 * Input:  scripts/thumbnail-sizes.json — per photo, the thumbnail width for the
 *         mobile/tablet tier (< 1024px) and the desktop tier (>= 1024px). The
 *         widths come from the boxes each photo really renders in, measured in a
 *         browser at 16 viewport widths (see the "rule" block in that file).
 * Output: public/thumbs/{mobile,desktop}/<original path>.webp (or .jpg when that is smaller)
 *         src/generated/thumbnails.ts — the manifest <Thumbnail> reads, with the
 *         real pixel size of every file for the img width/height attributes.
 *
 * The original aspect ratio is kept, so object-fit crops exactly as it did with
 * the original file - except where a photo renders in the same box shape at
 * every viewport (AspectRatio tiles): there it is centre-cropped to that shape,
 * which is exactly what object-fit: cover shows. Never wider than the original. The full
 * original is only loaded by the lightbox, when a visitor clicks to expand.
 *
 * Re-run after adding or replacing a photo, and add the photo to
 * thumbnail-sizes.json first. <Thumbnail> throws on a photo without a manifest
 * entry, so the SSG build fails instead of shipping a full-size image.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = resolve(root, 'public');
const outDir = resolve(publicDir, 'thumbs');
const spec = JSON.parse(readFileSync(resolve(root, 'scripts/thumbnail-sizes.json'), 'utf8'));

const WEBP = { quality: 75, effort: 6, smartSubsample: true };
const JPEG = { quality: 78, mozjpeg: true };

// URL-safe file name: srcset splits on whitespace, so a name like
// "photo_00-03-50 (2).jpg" must not keep its space or parentheses.
const safePath = (src, ext) =>
  src
    .replace(/^\//, '')
    .replace(/\.[a-z0-9]+$/i, '')
    .replace(/[^A-Za-z0-9._/-]+/g, '-')
    .replace(/-+$/, '') + ext;

const render = async (src, width, crop, tier) => {
  const input = resolve(publicDir, src.replace(/^\//, ''));
  if (!existsSync(input)) throw new Error(`Missing original: public${src}`);
  const original = readFileSync(input);
  const meta = await sharp(original).rotate().toBuffer({ resolveWithObject: true });
  const { width: ow, height: oh } = meta.info;

  // crop: the box's width/height ratio. Centre crop == what object-fit: cover shows.
  const resize = crop
    ? { width, height: Math.round(width / crop), fit: 'cover', position: 'centre', withoutEnlargement: true }
    : { width, withoutEnlargement: true };
  const pipeline = () => sharp(original).rotate().resize(resize); // rotate: honour EXIF like the browser

  const webp = await pipeline().webp(WEBP).toBuffer({ resolveWithObject: true });
  let out = { data: webp.data, info: webp.info, ext: '.webp' };

  // Not resized and not cropped: an already-small JPEG can beat WebP. Keep the smallest.
  const untouched = !crop && webp.info.width === ow && webp.info.height === oh;
  if (untouched && webp.data.length >= original.length * 0.95) {
    const jpeg = await pipeline().jpeg(JPEG).toBuffer({ resolveWithObject: true });
    out =
      jpeg.data.length < original.length
        ? { data: jpeg.data, info: jpeg.info, ext: '.jpg' }
        : { data: original, info: { width: ow, height: oh }, ext: '.jpg' };
  }

  const rel = `${tier}/${safePath(src, out.ext)}`;
  const file = resolve(outDir, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, out.data);
  return { src: `/thumbs/${rel}`, width: out.info.width, height: out.info.height, bytes: out.data.length };
};

rmSync(outDir, { recursive: true, force: true });

const manifest = {};
let originalBytes = 0;
let mobileBytes = 0;
let desktopBytes = 0;

for (const [src, { mobile, desktop, crop }] of Object.entries(spec.images)) {
  const m = await render(src, mobile, crop, 'mobile');
  // Same width for both tiers: share one file, so no second download.
  const d = desktop === mobile ? m : await render(src, desktop, crop, 'desktop');
  manifest[src] = {
    mobile: { src: m.src, width: m.width, height: m.height },
    desktop: { src: d.src, width: d.width, height: d.height },
  };
  originalBytes += readFileSync(resolve(publicDir, src.replace(/^\//, ''))).length;
  mobileBytes += m.bytes;
  desktopBytes += d.bytes;
}

const ts = `// GENERATED by scripts/generate-thumbnails.mjs — do not edit by hand.
// Re-run \`bun run thumbs\` after changing a photo or scripts/thumbnail-sizes.json.

export interface ThumbnailFile {
  src: string;
  width: number;
  height: number;
}

export interface ThumbnailEntry {
  /** Mobile and tablet, below DESKTOP_MIN_WIDTH. */
  mobile: ThumbnailFile;
  /** Desktop, from DESKTOP_MIN_WIDTH up. */
  desktop: ThumbnailFile;
}

/** Tailwind \`lg\`: the first width that gets the desktop thumbnail. */
export const DESKTOP_MIN_WIDTH = ${spec.rule.breakpoint_px};

export const thumbnails: Record<string, ThumbnailEntry> = ${JSON.stringify(manifest, null, 2)};
`;
mkdirSync(resolve(root, 'src/generated'), { recursive: true });
writeFileSync(resolve(root, 'src/generated/thumbnails.ts'), ts);

const kb = n => `${(n / 1024).toFixed(0)} KB`;
console.log(`[thumbs] ${Object.keys(manifest).length} photos`);
console.log(
  `[thumbs] originals ${kb(originalBytes)} | mobile set ${kb(mobileBytes)} | desktop set ${kb(desktopBytes)}`
);
